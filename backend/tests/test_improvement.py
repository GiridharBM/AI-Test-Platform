_CREATED = datetime.now(timezone.utc)


def _plan_for_add(target="add", file_path="app.py", args=("a", "b")):
    """TestPlan providing explicit edge-case evidence pinning every arg to None."""
    return TestPlan(
        project_id="p1", created_at=_CREATED,
        specs=[TestSpec(
            target_qualified_name=target, target_file=file_path, target_type="function",
            priority=1, test_type="unit", suggested_test_name=f"test_{target}",
            preconditions=[],
            edge_cases=[EdgeCase(parameter=a, case_type="none", description="None value")
                        for a in args],
            risk_score=0.5,
        )],
        summary=TestPlanSummary(total_specs=1, critical_count=1, high_count=0,
                                medium_count=0, low_count=0),
    )


def _finding(fid="f1", test_file="test_app.py", test_func="test_add",
             exc="NotImplementedError", category="exception"):
    return DiagnosisFinding(
        finding_id=fid,
        test_file=test_file,
        test_function=test_func,
        status="failed",
        failure_signature="sig",
        exception_type=exc,
        category=category,
    )


def _mk_codemap(**overrides):
    defaults = dict(
        project_id="p1",
        created_at=_CREATED,
        source_modules=[], test_functions=[], test_mappings=[], testable_targets=[],
        warnings=[],
    )
    defaults.update(overrides)
    return CodeMap(**defaults)


def _func_codemap(function_name="add", args=None, file_path="app.py", async_=False):
    fn = SourceFunction(
        name=function_name,
        qualified_name=function_name,
        file_path=file_path,
        line_start=1, line_end=3,
        args=args or ["a", "b"],
        is_async=async_,
    )
    mod = SourceModule(path=file_path, language="python", functions=[fn], classes=[])
    return _mk_codemap(source_modules=[mod], test_mappings=[
        TestMapping(
            test_function="test_add", test_file="test_app.py",
            source_target="add", source_file="app.py", confidence=0.9,
            method="import_analysis",
        )
    ])


def _diagnosis(findings):
    return DiagnosisResult(
        project_id="p1", created_at=_CREATED,
        overall_status="failures_diagnosed", findings=findings,
    )


def _placeholder_test_file():
    return (
        '"""Tests for app (auto-generated scaffold)."""\n'
        "\n"
        "def test_add():\n"
        '    """Test add.\n'
        '    """\n'
        '    raise NotImplementedError("Scaffold generated by AI Test Platform")\n'
        "\n"
        "def test_add_edge_a_none():\n"
        '    """Edge case: missing value."""\n'
        '    raise NotImplementedError("Edge case: missing value")\n'
        "\n"
    )


