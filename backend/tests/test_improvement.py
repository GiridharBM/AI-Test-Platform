    def test_containment_check_rejects_external_path(self, tmp_path):
        # Runs without symlink privileges: directly exercises the resolved-path
        # containment guard that defends the write path against directory
        # escapes (the symlink mechanism used by the test above).
        from app.services.improvement import _path_within
        gt = tmp_path / "p1" / "generated_tests"
        gt.mkdir(parents=True)
        outside = tmp_path / "outside" / "test_app.py"
