class TestImproveCore:
    def test_placeholder_function_improved(self, tmp_path):
        gt = tmp_path / "p1" / "generated_tests"
        gt.mkdir(parents=True)
        (gt / "test_app.py").write_text(_placeholder_test_file(), encoding="utf-8")

        result = improve_diagnosis(
            _diagnosis([_finding()]), _func_codemap(), tmp_path, "p1",
            test_plan=_plan_for_add(),
        )
        assert result.status == "improved"
        assert result.files_modified == 1
        assert len(result.changes) == 1
        ch = result.changes[0]
        assert ch.status == "improved"
        assert ch.test_file == "test_app.py"
        assert "add" in ch.after
        assert "Scaffold generated by AI Test Platform" not in ch.after
        assert "assert result == " not in ch.after  # never fabricate a value

        # The improved file on disk reflects the change.
        on_disk = (gt / "test_app.py").read_text(encoding="utf-8")
        assert "def test_add():" in on_disk
        assert "from app import add" in on_disk
        assert "add(None, None)" in on_disk
        assert "add(0, 0)" not in on_disk  # no fabricated 0-valued inputs
        # sibling edge-case helper is untouched
        assert "test_add_edge_a_none" in on_disk
        assert "Edge case: missing value" in on_disk

